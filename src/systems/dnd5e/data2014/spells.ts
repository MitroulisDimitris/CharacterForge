const base = new Map(SPELLS_2024.map((s) => [s.name, s]));

/** A 2014 spell built from the 2024 entry plus overrides. */
function from(name: string, o: Partial<Spell> = {}): Spell {
  const b = base.get(name);
  if (!b) throw new Error(`No base spell ${name}`);
  return { ...b, ...o, book: o.book ?? "PHB14", sorcerer: o.sorcerer ?? true };
}

